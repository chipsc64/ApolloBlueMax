#!/usr/bin/env python3
"""Generate include/bm_status_font.h: an original 8x8 font for the 64 Atari
internal character codes used by the mode-6 status line (DLIR sets CHBASE to
the OS ROM font).  The glyphs are drawn here in the same blocky two-pixel
stroke style; they are not copied from the Atari ROM."""
