#!/usr/bin/env python3
"""Generate bm_music_data.h from MAX.4: the three PLAY.IT voices (EXXON.18).
MAX.4 loads at $4D00; the game copies it to DL+$500, so the voices start at
offsets $000, $0CB and $17C (VOICE.1/2/3 = DL+$500/$5CB/$67C).  Each voice
is (note, duration) pairs ended by $FF."""
import sys

def main(source, target):
    d = open(source, 'rb').read()
    assert d[:2] == b'\xff\xff'
    start = d[2] | d[3] << 8
    end = d[4] | d[5] << 8
    assert start == 0x4D00, hex(start)
    data = d[6:6 + end - start + 1]
    offsets = (0x000, 0x0CB, 0x17C)
    voices = []
    for o in offsets:
        e = data.index(0xFF, o)
        assert (e - o) % 2 == 0, hex(o)
        voices.append(data[o:e + 1])
    out = ['/* Generated by tools/music_data.py from MAX.4 - do not edit. */',
           '#ifndef BM_MUSIC_DATA_H', '#define BM_MUSIC_DATA_H', '#include <stdint.h>']
    for i, v in enumerate(voices, 1):
        out.append(f'static const uint8_t bm_music_voice{i}[{len(v)}] = {{')
        for k in range(0, len(v), 16):
            out.append('  ' + ','.join(f'0x{b:02x}' for b in v[k:k + 16]) + ',')
        out.append('};')
    out.append('#endif')
    open(target, 'w').write('\n'.join(out) + '\n')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
