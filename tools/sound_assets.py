#!/usr/bin/env python3
"""Generate bm_sound_assets.h from the samples in sounds/ (SOUND=samples).

sounds/NAME.wav       a sample for one game sound (NAME from SAMPLES below,
                      in BmSampleId order, bm_sound.h).  Sounds without a
                      file keep their original POKEY sound.

WAV files are decoded here (PCM, 8 or 16 bit, mono or stereo, any rate) so
no Python packages are needed.  Stereo is mixed to mono; the sample keeps
its own rate, the mixer converts it."""
import os
import struct
import sys

# BmSampleId order (bm_sound.h).
SAMPLES = ['engine', 'engine_dying', 'attacker_engine', 'gun_own', 'gun_enemy',
           'ground_gun', 'flak', 'bomb_whistle', 'explosion_small',
           'explosion_medium', 'explosion_large', 'splash', 'runway']
MAX_SECONDS = 10


def read_wav(path):
    data = open(path, 'rb').read()
    if data[:4] != b'RIFF' or data[8:12] != b'WAVE':
        raise SystemExit(f'{path}: not a WAV file')
    pos, fmt, pcm = 12, None, None
    while pos + 8 <= len(data):
        kind, length = data[pos:pos + 4], struct.unpack('<I', data[pos + 4:pos + 8])[0]
        body = data[pos + 8:pos + 8 + length]
        if kind == b'fmt ':
            fmt = struct.unpack('<HHIIHH', body[:16])
        elif kind == b'data':
            pcm = body
        pos += 8 + length + (length & 1)
    if not fmt or pcm is None:
        raise SystemExit(f'{path}: no fmt or data chunk')
    code, channels, rate, _, _, bits = fmt
    if code != 1 or bits not in (8, 16) or channels not in (1, 2):
        raise SystemExit(f'{path}: use PCM WAV, 8 or 16 bit, mono or stereo')
    if bits == 16:
        values = struct.unpack(f'<{len(pcm) // 2}h', pcm[:len(pcm) // 2 * 2])
    else:
        values = [(v - 128) << 8 for v in pcm]
    if channels == 2:
        values = [(values[i] + values[i + 1]) // 2 for i in range(0, len(values) - 1, 2)]
    if len(values) > rate * MAX_SECONDS:
        raise SystemExit(f'{path}: at most {MAX_SECONDS} seconds')
    return rate, list(values)


def main(sound_dir, target):
    found = {}
    if os.path.isdir(sound_dir):
        for name in sorted(os.listdir(sound_dir)):
            stem, ext = os.path.splitext(name)
            if ext.lower() != '.wav':
                continue
            if stem not in SAMPLES:
                raise SystemExit(f'{name}: unknown sound (use one of {", ".join(SAMPLES)})')
            found[stem] = read_wav(os.path.join(sound_dir, name))
    out = ['/* Generated by tools/sound_assets.py from sounds/ - do not edit. */',
           '#ifndef BM_SOUND_ASSETS_H', '#define BM_SOUND_ASSETS_H', '#include "bm_mixer.h"',
           f'enum {{ BM_SAMPLE_FILES = {len(SAMPLES)} }};']
    for stem, (rate, values) in found.items():
        out.append(f'static const int16_t bm_sample_{stem}_data[{len(values)}] = {{')
        for k in range(0, len(values), 16):
            out.append('  ' + ','.join(str(v) for v in values[k:k + 16]) + ',')
        out.append('};')
        out.append(f'static const BmSample bm_sample_{stem} = {{ bm_sample_{stem}_data, '
                   f'{len(values)}u, {rate}u }};')
    out.append('/* Per BmSampleId: its sample, or 0 (the POKEY sound). */')
    out.append('static const BmSample *const bm_samples[BM_SAMPLE_FILES] = {')
    for stem in SAMPLES:
        out.append(f'  &bm_sample_{stem},' if stem in found else '  0,')
    out.append('};')
    out.append('#endif')
    os.makedirs(os.path.dirname(target), exist_ok=True)
    open(target, 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
